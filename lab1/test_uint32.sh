#!/bin/sh

set -eu

PROGRAM="./prg1mamN3149"
TEST_NUMBER=0

run_test() {
    input=$1
    expected=$2
    actual=$($PROGRAM "$input" | tail -n 1)
    TEST_NUMBER=$((TEST_NUMBER + 1))

    if [ "$actual" != "$expected" ]; then
        echo "uint32_t: тест $TEST_NUMBER не пройден" >&2
        echo "Число: $input" >&2
        echo "Ожидалось: $expected" >&2
        echo "Получено:  $actual" >&2
        exit 1
    fi
}

# 00000000 00000000 00000000 00000000  исходное
# 00000000 00000000 00000000 00000000  изменённое
run_test 0 "00000000 00000000 00000000 00000000"
