# 11011110 10101101 10111110 11101111  исходное
# 11011110 11101111 10111110 10101101  изменённое
run_test 3735928559 "11011110 11101111 10111110 10101101"
# 00000001 00000010 00000011 00000100  исходное
# 00000001 00000010 00000011 00000100  изменённое
run_test 16909060 "00000001 00000010 00000011 00000100"
# 10101101 11101111 00110011 01000100  исходное
# 11101111 10101101 00110011 01000100  изменённое
run_test 2918134596 "11101111 10101101 00110011 01000100"
# 01010101 10101010 00010010 00110100  исходное
# 01010101 10101010 00010010 00110100  изменённое
run_test 1437209140 "01010101 10101010 00010010 00110100"
# 11101111 00000001 00000010 00000011  исходное
# 11101111 00000001 00000010 00000011  изменённое
run_test 4009820675 "11101111 00000001 00000010 00000011"
# 10101101 00110100 00000001 00000010  исходное
# 00110100 10101101 00000001 00000010  изменённое
run_test 2905866498 "00110100 10101101 00000001 00000010"
# 00010010 00110100 01010110 01111000  исходное
# 00010010 01010110 00110100 01111000  изменённое
run_test 305419896 "00010010 01010110 00110100 01111000"
